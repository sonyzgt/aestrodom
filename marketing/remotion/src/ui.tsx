/** Mouse pointer gliding through `points` ([frame, x, y]) and dipping on each frame in `clicks`. */
export function Cursor({ points, clicks = [], start = 0 }: { points: [number, number, number][]; clicks?: number[]; start?: number }) {
  const frame = useCurrentFrame();
  // Clicks are audible even before the pointer is drawn, so the audio tree is always mounted.
  const sounds = clicks.map((c) => <Sfx key={c} at={c} name="click" volume={0.9} />);
  if (frame < start) return <>{sounds}</>;
  const frames = points.map((p) => p[0]);
  const x = interpolate(frame, frames, points.map((p) => p[1]), { extrapolateLeft: "clamp", extrapolateRight: "clamp", easing: Easing.inOut(Easing.cubic) });
  const y = interpolate(frame, frames, points.map((p) => p[2]), { extrapolateLeft: "clamp", extrapolateRight: "clamp", easing: Easing.inOut(Easing.cubic) });
  const press = clicks.reduce((s, c) => Math.min(s, frame >= c && frame < c + 8 ? interpolate(frame, [c, c + 3, c + 8], [1, 0.8, 1]) : 1), 1);
  const ring = clicks.find((c) => frame >= c && frame < c + 16);
  return (
    <div style={{ position: "absolute", left: x, top: y, zIndex: 50, pointerEvents: "none" }}>
      {sounds}
      {ring !== undefined && (
        <div
          style={{
            position: "absolute",
            left: -22,
            top: -22,
            width: 44,
            height: 44,
            borderRadius: 22,
            border: `2px solid ${C.ink}`,
            opacity: interpolate(frame, [ring, ring + 16], [0.5, 0]),
            transform: `scale(${interpolate(frame, [ring, ring + 16], [0.4, 1.3])})`,
          }}
        />
      )}
      <svg width="30" height="30" viewBox="0 0 24 24" style={{ transform: `scale(${press})`, transformOrigin: "4px 3px", filter: "drop-shadow(0 3px 5px rgba(0,0,0,0.25))" }}>
        <path d="M4 3 L4 19 L8.5 14.8 L11.4 21 L14 19.8 L11.2 13.8 L17.5 13.6 Z" fill={C.ink} stroke="#fff" strokeWidth="1.4" strokeLinejoin="round" />
      </svg>
    </div>
  );
}


/** Black primary button, as on the site; `pressed` (0..1) darkens and shrinks it a touch. */
export function Button({ children, pressed = 0, style }: { children: React.ReactNode; pressed?: number; style?: React.CSSProperties }) {
  return (
    <div
      style={{
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
        gap: 10,
        height: 52,
        padding: "0 26px",
        borderRadius: 8,
        background: C.ink,
        color: "#fff",
        fontFamily: sans,
        fontWeight: 600,
        fontSize: 17,
        letterSpacing: "0.14em",
        textTransform: "uppercase",
        transform: `scale(${1 - pressed * 0.04})`,
        opacity: 1 - pressed * 0.15,
        ...style,
      }}
    >
      {children}
    </div>
  );
}

/** 0 → 1 → 0 over a click at `at`, for Button's `pressed`. */
export function pressAt(frame: number, at: number) {
  return interpolate(frame, [at, at + 3, at + 9], [0, 1, 0], { extrapolateLeft: "clamp", extrapolateRight: "clamp" });
}


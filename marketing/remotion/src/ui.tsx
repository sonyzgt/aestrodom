const OUT = Easing.bezier(0.22, 1, 0.36, 1);

/** interpolate() clamped at both ends with a soft ease-out, the default motion curve of the video. */
export function ease(frame: number, input: [number, number], output: [number, number], easing = OUT) {
  return interpolate(frame, input, output, { extrapolateLeft: "clamp", extrapolateRight: "clamp", easing });
}

/** Fade + rise for an element entering at `start`. */
export function rise(frame: number, start: number, distance = 24, duration = 18): React.CSSProperties {
  return {
    opacity: ease(frame, [start, start + duration], [0, 1]),
    transform: `translateY(${ease(frame, [start, start + duration], [distance, 0])}px)`,
  };
}

/** The visible part of `text` when typing starts at `start` at `cps` characters per second (30 fps). */
export function typed(text: string, frame: number, start: number, cps = 28) {
  const n = Math.floor(((frame - start) * cps) / 30);
  return text.slice(0, Math.max(0, Math.min(text.length, n)));
}


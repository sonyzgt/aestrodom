export type SfxName = "click" | "key1" | "key2" | "key3" | "whoosh" | "tick" | "chime" | "pop" | "swell";

/** One sound effect starting at scene frame `at`. */
export function Sfx({ at, name, volume = 1 }: { at: number; name: SfxName; volume?: number }) {
  return (
    <Sequence from={Math.round(at)} durationInFrames={60} layout="none">
      <Html5Audio src={staticFile(`sfx/${name}.wav`)} volume={volume} />
    </Sequence>
  );
}

/** A key click for every character `typed(text, frame, start, cps)` reveals, one per frame at most. */
export function TypingSound({ text, start, cps = 28, volume = 0.3 }: { text: string; start: number; cps?: number; volume?: number }) {
  const frames = new Set<number>();
  for (let i = 0; i < text.length; i++) frames.add(start + Math.ceil(((i + 1) * 30) / cps));
  return (
    <>
      {[...frames].map((f, i) => (
        <Sfx key={f} at={f} name={(["key1", "key2", "key3"] as const)[(i * 7) % 3]} volume={volume * (0.8 + 0.2 * ((i * 5) % 3))} />
      ))}
    </>
  );
}

